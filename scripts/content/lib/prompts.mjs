/** Промпт написания статьи по собранной фактуре. */
export function writePrompt({ topic, research, linkCandidates, dateStr, reviewDate }) {
	const links = linkCandidates
		.map((l) => `- [${l.title}](/blog/${l.slug}/) — категория ${l.category}`)
		.join('\n');

	return [
		{
			role: 'system',
			content:
				'Ты — редактор медиа «Этикетка» (etiketka-media.ru) о требованиях к малому бизнесу в РФ: ' +
				'ТС ПИоТ, маркировка «Честный знак», кассы, ЕГАИС, налоги. Пишешь по-русски, ' +
				'строго по редполитике, только на подтверждённой фактуре. ' +
				'Возвращаешь готовый файл MDX и ничего больше.',
		},
		{
			role: 'user',
			content: `Напиши статью «${topic.title}».

Целевой поисковый запрос: «${topic.keyword}» — он должен читаться в title,
в первом абзаце и хотя бы в одном H2.

ФАКТУРА (единственный допустимый источник цифр, дат и номеров НПА —
ничего не добавляй от себя):
${JSON.stringify(research, null, 1)}

Не используй утверждения из поля "uncertain". Если факта нет в фактуре —
не пиши его.

${VOICE}

${STRUCTURE}

ПЕРЕЛИНКОВКА: минимум ${LIMITS.internalLinksMin} ссылки на статьи из списка ниже,
только на них, точно в таком написании URL. Ссылки вплетай в текст по смыслу,
не списком в конце.
${links}

CPA-ВРЕЗКА: ровно одна, после 2-й или 3-й секции H2, строкой
<CpaCallout id="${topic.cpa ?? 'default-' + topic.category}" />
Перед ней — один абзац подводки в духе «если разбираться в одиночку времени нет».
Без рекламных эпитетов и без обещаний.

Формат ответа — файл целиком, начиная с frontmatter:

---
title: "…"                       # ${LIMITS.titleMin}–${LIMITS.titleMax} символов, с целевым ключом
description: "…"                 # 140–160 символов, с ключом
pubDate: "${dateStr}"
reviewDate: "${reviewDate}"
tags:
  - …                            # ${LIMITS.tagsMin}–${LIMITS.tagsMax} тегов, строчными
categories:
  - ${topic.category}
draft: true
cpa: '${topic.cpa ?? 'default-' + topic.category}'
seo:
  keywords:
    - ${topic.keyword}
    - …                          # ещё 2–3 связанных ключа
---

import CpaCallout from '../../components/CpaCallout.astro';

<текст статьи>

Никаких комментариев до или после файла, не оборачивай ответ в \`\`\`.`,
		},
	];
}

/** Промпт починки: модель получает список конкретных претензий валидатора. */
export function repairPrompt({ article, problems }) {
	return [
		{
			role: 'system',
			content:
				'Ты — редактор медиа «Этикетка». Исправляешь статью точечно по списку претензий, ' +
				'сохраняя фактуру и структуру. Возвращаешь исправленный файл MDX целиком и ничего больше.',
		},
		{
			role: 'user',
			content: `Статья не прошла шлюз качества. Претензии:

${problems.map((p, i) => `${i + 1}. ${p}`).join('\n')}

Исправь ровно это, не переписывая остальное и не добавляя новых фактов, дат,
сумм и номеров НПА. Если претензия про несуществующую внутреннюю ссылку —
замени её на ссылку из уже присутствующих в тексте или убери, добрав нужное
число ссылок из тех, что уже есть в статье.

${VOICE}

Файл:

${article}`,
		},
	];
}

/** Промпт фактчека готовой статьи с веб-поиском. */
export function factcheckPrompt({ article, npaUnknown }) {
	return [
		{
			role: 'system',
			content:
				'Ты — фактчекер российского делового медиа. Сверяешь утверждения статьи с ' +
				'первоисточниками через веб-поиск. Скептичен: «не нашёл подтверждения» — ' +
				'нормальный и частый ответ. Возвращаешь только JSON.',
		},
		{
			role: 'user',
			content: `Проверь фактуру статьи. Сегодня ${new Date().toISOString().slice(0, 10)}.

Обязательно проверь каждый номер НПА из этого списка — существует ли такой
документ, о чём он и действует ли он сейчас:
${npaUnknown.length ? npaUnknown.map((u) => `- ${u.label}`).join('\n') : '- (нет неизвестных номеров)'}

Кроме того проверь: все даты вступления норм в силу, все суммы штрафов
и части статей КоАП, все утверждения об обязанностях бизнеса.

Верни JSON:
{
  "verdict": "ok" | "needs-fix",
  "npa": [{"label": "ПП № 1944", "kind": "pp", "number": "1944",
           "exists": true|false, "title": "официальное название",
           "source": "https://…"}],
  "claims": [{"quote": "цитата из статьи", "status": "match"|"mismatch"|"unverified",
              "expected": "как правильно", "source": "https://…", "severity": "critical"|"moderate"|"minor"}],
  "fixes": ["конкретная правка для редактора", "…"]
}

verdict = "needs-fix", если хотя бы один НПА не существует или есть claim
со статусом mismatch и severity critical.

Статья:

${article}`,
		},
	];
}

